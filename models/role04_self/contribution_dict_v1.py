# ── 수치 표현 패턴 (정규식) ─────────────────────────────────
CONTRIBUTION_NUMBER_PATTERNS = [
    # 비율·배율 — 개선 수치로 신뢰도 높음
    r"\d+\s*%",
    r"\d+\s*배",
    # 순위·등수 — 성과 지표
    r"\d+\s*위",
    r"\d+\s*등",
    r"상위\s*\d+\s*%",
    # 금액 — 매출·절감 등 구체 성과
    r"\d+\s*만\s*원",
    r"\d+\s*억\s*원",
    r"\d+\s*천\s*원",
    r"\d+\s*달러",
    r"\d+\s*위안",
    # 물리량 — 거리·시간 단축 등
    r"\d+\s*cm",
    r"\d+\s*m\b",
    r"\d+\s*km",
    r"\d+\s*시간",   # '3시간 단축' 같은 경우에 유효
    # 점수
    r"\d+\s*점",
    # '명', '건', '개', '일', '주', '회' 는 너무 범용적이어서 제외
]


def has_number_expression(text: str) -> list:
    """텍스트에서 수치 표현 패턴을 탐지해 매칭 결과 반환 (중복 제거)"""
    spans = []
    for pattern in CONTRIBUTION_NUMBER_PATTERNS:
        for m in re.finditer(pattern, text):
            spans.append((m.start(), m.end(), m.group()))

    spans.sort(key=lambda x: (x[0], -(x[1] - x[0])))
    result, last_end = [], -1
    for start, end, matched in spans:
        if start >= last_end:
            result.append(matched)
            last_end = end
    return result
